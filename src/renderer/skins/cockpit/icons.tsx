import type { ComponentType, JSX } from 'react';

import type { IconProps, IconSet } from '../types';

/**
 * Desk glyphs: 12×12 pixel bitmaps, drawn with crisp edges so they stay sharp at the small
 * sizes a dense terminal uses. Each map is written as rows of '#' (ink) and '.' (paper).
 */
function path(rows: readonly string[]): string {
	let d = '';
	rows.forEach((row, y) => {
		for (const m of row.matchAll(/#+/g))
			d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
	});
	return d;
}

function glyph(rows: readonly string[]): ComponentType<IconProps> {
	const d = path(rows);
	function Glyph({ size, className }: IconProps): JSX.Element {
		return (
			<svg
				width={size}
				height={size}
				viewBox='0 0 12 12'
				fill='currentColor'
				shapeRendering='crispEdges'
				className={className}
				aria-hidden
			>
				<path d={d} />
			</svg>
		);
	}
	return Glyph;
}

